const TERM_RES=Object.keys(GLOSSARY).filter(k=>!SKIP.includes(k)).map(k=>[k,new RegExp(MATCH[k]||k.replace(/[.*+?^${}()|[\]\\]/g,'\\$&'))]);
function glossify(text){const hits=[];
for(const [k,re] of TERM_RES){const m=re.exec(text);if(m)hits.push({k,i:m.index,e:m.index+m[0].length,t:m[0]})}
hits.sort((p,q)=>p.i-q.i||(q.e-q.i)-(p.e-p.i));
const keep=[];let end=-1;for(const h of hits){if(h.i>=end){keep.push(h);end=h.e}}
let out='',i=0;for(const h of keep){out+=esc(text.slice(i,h.i))+`<button class="term" data-term="${esc(h.k)}" aria-expanded="false">${esc(h.t)}</button>`;i=h.e}
return out+esc(text.slice(i))}
